/**
 * Offer PDF (CAB branding) generated in the browser from an `OfferItem`:
 * client and application details, fee lines, discount and total, commercial terms
 * and the offer history. Used by the offer register (CAB and client portal) and the
 * offer detail view.
 */

import type { TFunction } from 'i18next'
import type { OfferItem } from '@/lib/api/cabOffersApi'
import { BrandedDocument, loadCabBranding } from '@/lib/pdf/brandedDocument'
import { notSet } from '@/lib/emptyValue'

const money = (value: number, currency: string, locale: string) => {
  try {
    return new Intl.NumberFormat(locale, { style: 'currency', currency, maximumFractionDigits: 2 }).format(value)
  } catch {
    return `${value.toFixed(2)} ${currency}`
  }
}

export function offerTotals(offer: Pick<OfferItem, 'fees' | 'optionalDiscount'>) {
  const subtotal = offer.fees.reduce((sum, fee) => sum + (Number(fee.amount) || 0), 0)
  const discount = Number(offer.optionalDiscount) || 0
  return { subtotal, discount, total: Math.max(0, subtotal - discount) }
}

/** Builds and downloads `<offer number>.pdf`. */
export async function downloadOfferPdf(offer: OfferItem, t: TFunction, language: string): Promise<void> {
  const branding = await loadCabBranding()
  const rtl = language.startsWith('ar')
  const doc = new BrandedDocument(branding, {
    title: `${t('cab.offerDetail.pdfTitle', 'Offer')} ${offer.offerNumber}`,
    rtl,
    footerNote: t('cab.offerDetail.pdfFooter', 'Generated by iCASCO'),
  })
  const revision = offer.revision && offer.revision > 1 ? ` · ${t('cab.offerDetail.revision', 'Revision')} ${offer.revision}` : ''
  doc.header(t('cab.offerDetail.pdfTitle', 'Offer'), `${offer.offerNumber}${revision}`)

  doc.section(t('cab.offerDetail.sections.client', 'Client'))
  doc.fields([
    [t('cab.offerDetail.fields.client', 'Client'), `${offer.clientName} (${offer.clientCode})`],
    [t('cab.offerDetail.fields.country', 'Country'), offer.country],
    [t('cab.offerDetail.fields.contact', 'Primary contact'), offer.primaryContact],
    [t('cab.offerDetail.fields.email', 'E-mail'), offer.contactEmail],
  ])

  doc.section(t('cab.offerDetail.sections.application', 'Application'))
  doc.fields([
    [t('cab.offerDetail.fields.application', 'Application'), offer.relatedApplication],
    [t('cab.offerDetail.fields.standard', 'Standard'), offer.applicationStandard],
    [t('cab.offerDetail.fields.scope', 'Scope'), offer.applicationScope],
    [t('cab.offerDetail.fields.status', 'Status'), t(`cab.offersPage.status.${offer.status}`, offer.statusLabel)],
  ])

  doc.section(t('cab.offerDetail.sections.fees', 'Fees'))
  doc.table(
    [
      { header: '#', width: 0.6 },
      { header: t('cab.offerDetail.fields.description', 'Description'), width: 6 },
      { header: `${t('cab.offerDetail.fields.amount', 'Amount')} (${offer.currency})`, width: 2.4, align: 'end' },
    ],
    offer.fees.map((fee, i) => [String(i + 1), fee.description, money(fee.amount, offer.currency, language)]),
  )
  const { subtotal, discount, total } = offerTotals(offer)
  doc.totals([
    [t('cab.offerDetail.subtotal', 'Subtotal'), money(subtotal, offer.currency, language)],
    ...(discount ? ([[t('cab.offerDetail.discount', 'Discount'), `- ${money(discount, offer.currency, language)}`]] as Array<[string, string]>) : []),
    [t('cab.offerDetail.total', 'Total (before tax)'), money(total, offer.currency, language), true],
  ])

  doc.section(t('cab.offerDetail.sections.terms', 'Commercial terms'))
  doc.fields([
    [t('cab.offerDetail.fields.validUntil', 'Valid until'), offer.validUntil],
    [t('cab.offerDetail.fields.paymentTerms', 'Payment terms'), offer.paymentTerms],
    [t('cab.offerDetail.fields.travel', 'Travel costs'), t(`cab.createOffer.travel.${offer.travelCosts.toLowerCase()}`, offer.travelCosts)],
    [t('cab.offerDetail.fields.terms', 'Terms attachment'), offer.termsAttachmentName ?? notSet()],
  ])
  if (offer.notes) doc.paragraph(offer.notes)

  if (offer.history?.length) {
    doc.section(t('cab.offerDetail.sections.history', 'History'))
    doc.table(
      [
        { header: t('cab.offerDetail.fields.date', 'Date'), width: 2 },
        { header: t('cab.offerDetail.fields.action', 'Action'), width: 5 },
        { header: t('cab.offerDetail.fields.by', 'By'), width: 3 },
      ],
      offer.history.map((h) => [h.date, h.action, h.by]),
    )
  }

  doc.save(`${offer.offerNumber}.pdf`, (page, count) => t('cab.offerDetail.page', { defaultValue: 'Page {{page}} of {{count}}', page, count }))
}
