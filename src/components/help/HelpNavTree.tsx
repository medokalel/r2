import { useState } from 'react'
import { Link } from 'react-router-dom'
import { useTranslation } from 'react-i18next'
import { Home2 } from 'iconsax-reactjs'
import { AppIcon, ChevronDownIcon } from '@/components/icons'
import { sectionIcon } from '@/components/help/helpIcons'
import { helpArticlePath, helpOverviewPath, helpSectionPath } from '@/lib/help/paths'
import type { HelpSection } from '@/lib/help/registry'
import type { HelpAudience, HelpLang } from '@/lib/help/types'
import { cn } from '@/lib/utils'

interface Props {
  sections: HelpSection[]
  audience: HelpAudience
  lang: HelpLang
  activeSectionId?: string
  activeArticleId?: string
  onNavigate?: () => void
}

/** Left (right in Arabic) tree of help sections and their articles, collapsible per section. */
export function HelpNavTree({ sections, audience, lang, activeSectionId, activeArticleId, onNavigate }: Props) {
  const { t } = useTranslation()
  const [open, setOpen] = useState<Record<string, boolean>>({})
  const isOpen = (id: string) => open[id] ?? (id === activeSectionId || !activeSectionId)

  return (
    <nav aria-label={t('help.nav.label')} className="flex flex-col gap-1 text-body-sm">
      <Link
        to={helpOverviewPath(audience)}
        onClick={onNavigate}
        aria-current={!activeSectionId ? 'page' : undefined}
        className={cn(
          'flex items-center gap-2.5 rounded-md px-3 py-2 font-medium transition-colors',
          !activeSectionId ? 'bg-bg-brand-light text-primary' : 'text-text-primary hover:bg-bg-hover',
        )}
      >
        <AppIcon icon={Home2} size={18} className="shrink-0" />
        {t('help.nav.home')}
      </Link>
      {sections.map((section) => {
        const expanded = isOpen(section.id)
        return (
          <div key={section.id} className="mt-1">
            <div className="flex items-center rounded-md hover:bg-bg-hover">
              <Link
                to={helpSectionPath(section.id)}
                onClick={onNavigate}
                className={cn(
                  'flex min-w-0 flex-1 items-center gap-2.5 px-3 py-2 font-semibold',
                  section.id === activeSectionId && !activeArticleId ? 'text-primary' : 'text-text-primary',
                )}
              >
                <AppIcon icon={sectionIcon(section.id)} size={18} className="shrink-0 text-icon-brand" />
                <span className="min-w-0 flex-1 truncate">{section.title[lang]}</span>
              </Link>
              <button
                type="button"
                onClick={() => setOpen((prev) => ({ ...prev, [section.id]: !expanded }))}
                aria-expanded={expanded}
                aria-label={section.title[lang]}
                className="flex size-8 shrink-0 items-center justify-center rounded-md text-icon-secondary hover:text-primary"
              >
                <AppIcon icon={ChevronDownIcon} size={16} className={cn('transition-transform', expanded && 'rotate-180')} />
              </button>
            </div>
            {expanded && (
              <ul className="ms-5 mt-0.5 flex flex-col gap-0.5 border-s border-border-default ps-2">
                {section.articles.map((article) => {
                  const active = section.id === activeSectionId && article.id === activeArticleId
                  return (
                    <li key={article.id}>
                      <Link
                        to={helpArticlePath(section.id, article.id)}
                        onClick={onNavigate}
                        aria-current={active ? 'page' : undefined}
                        className={cn(
                          'relative flex items-center gap-2 rounded-md px-3 py-1.5 leading-snug transition-colors',
                          active ? 'bg-bg-brand-light font-semibold text-primary' : 'text-text-secondary hover:bg-bg-hover hover:text-text-primary',
                        )}
                      >
                        {active && <span aria-hidden className="absolute -start-[9px] inset-y-1 w-0.5 rounded-full bg-primary" />}
                        <span className="min-w-0 flex-1">{article.text[lang].title}</span>
                        {article.stub && <span className="size-1.5 shrink-0 rounded-full bg-warning-500" title={t('help.article.autoGenerated')} />}
                      </Link>
                    </li>
                  )
                })}
              </ul>
            )}
          </div>
        )
      })}
    </nav>
  )
}
